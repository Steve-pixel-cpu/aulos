f = Path('static/i18n/en.js')
lines = f.read_text(encoding='utf-8').split('\n')
hits = 0
for i, line in enumerate(lines):
    m = re.match(r'^(\s*)"([a-z_.0-9]+)":\s*(.*?),?\s*$', line)
    if not m:
        continue
    key = m.group(2)
    if key not in T:
        continue
    lines[i] = f'{m.group(1)}"{key}": {json.dumps(T[key], ensure_ascii=False)},'
    hits += 1
f.write_text('\n'.join(lines), encoding='utf-8', newline='')
print(f'替换 {hits} 行 (表 {len(T)})')
resid = [l for l in lines if re.search(r'[\u4e00-\u9fff]', l) and re.match(r'^\s*"[a-z_.0-9]+":', l)]
print('剩余中文条目:', len(resid))
for l in resid[:6]:
    print(' ', l.strip()[:100])
